"""Read-only dialog and IME layout checks; does not submit network inputs."""
import time
from device_lab import adb,verify_device,launch
from ui_lab import ui,find,tap,tap_node,screenshot
from glass_gesture_regression import record,input_cmd,show,pause,bounds
verify_device(); input_cmd('motionevent CANCEL 0 0')
adb('shell','am','force-stop','com.sweefl.player')
adb('shell','am','start','-W','-f','0x10008000','-n','com.sweefl.player/.MainActivity')
tap(ui('library'),'设置'); tree=ui('settings')
record('settings dialog opens',find(tree,'Sweefl Player') is not None); screenshot('settings')
tap(show('手势与进度预览','settings-gesture-entry'),'手势与进度预览'); tree=ui('library-gestures')
record('library exposes shared gesture settings',find(tree,'左侧区域') is not None); screenshot('library-gestures')
tap(tree,'完成'); tap(ui('settings-return'),'完成')
tap(ui('network-entry'),'打开网络视频'); tree=ui('network')
record('network dialog uses accessible editable inputs',len([n for n in tree.iter('node') if n.get('class')=='android.widget.EditText'])==2)
screenshot('network')
tap_node(next(n for n in tree.iter('node') if n.get('class')=='android.widget.EditText'))
input_cmd('text https://example.com/video.mp4'); tree=ui('network-ime'); screenshot('network-ime')
record('network URL remains editable with keyboard',any(n.get('class')=='android.widget.EditText' and 'https://example.com/video.mp4' in n.get('text','') and n.get('focused')=='true' for n in tree.iter('node')))
button=find(tree,'播放'); record('network action stays reachable with keyboard',button is not None and bounds(button)[3]>bounds(button)[1])
input_cmd('keyevent 4'); tap(ui('network-cancel'),'取消')
launch('synthetic/avc1080.mp4',extra=('--ez','keepControls','true'),key='dialog-portrait')
pause('portrait-paused'); tree=ui('portrait-orientation')
x1,y1,x2,y2=bounds(next(tree.iter('node')))
if x2-x1>y2-y1: tap(tree,'切换横竖屏'); ui('portrait-ready')
tap(ui('portrait-gesture-entry'),'手势与进度预览'); tree=ui('portrait-gestures')
record('portrait gesture dialog keeps all region choices reachable',all(find(show(label,'portrait-region'),label) is not None for label in ['左侧区域','中间区域','右侧区域']))
tree=ui('portrait-gestures-scrolled')
screenshot('portrait-gestures'); tap(tree,'完成')
tap(ui('rotate'),'切换横竖屏'); tree=ui('landscape')
tap(tree,'手势与进度预览'); tree=ui('landscape-gestures'); screenshot('landscape-gestures')
tap(show('右侧区域','landscape-right'),'右侧区域'); tree=show('锁定触控','landscape-nested-lock'); screenshot('landscape-nested-actions')
record('nested gesture action remains reachable in landscape',find(tree,'锁定触控') is not None)
input_cmd('keyevent 4'); tap(ui('landscape-gesture-done'),'完成')
tap(ui('speed-entry'),'1.0×'); tree=ui('speed'); screenshot('speed')
record('last speed option reachable in landscape',find(show('3.0×','speed-scroll'),'3.0×') is not None)
input_cmd('keyevent 4'); screenshot('final-player')
adb('shell','am','force-stop','com.sweefl.player')
print('Dialog checks finished.',flush=True)
